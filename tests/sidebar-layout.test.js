assert.match(css, /\.tabs\{[^}]*overflow-x:auto/);
assert.match(css, /\.tab\{[^}]*border-radius:7px 7px 0 0/);
assert.match(js, /groupModelSearch'\)\.addEventListener\('input', renderGroupModels\)/);
